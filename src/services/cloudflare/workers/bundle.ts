/**
 * bundle.ts: reads + checks the prebuilt Worker bundle inside the app folder (CONTRACTS.md §1.3), and the D1 migrations folder.
 *
 *   <bundleDir>/bundle.json       { mainModule, modules: [{ name, type }], compatibilityDate, compatibilityFlags?,
 *                                    assets?: { dir, binding?, config? }, migrations?, crons?, …other fields are ignored }
 *   crons: the Worker's Cron Triggers (5-field cron, UTC). Declared = deployBundle replaces the Worker's schedules with
 *   exactly this list ([] turns them all off); not declared = schedules are left untouched.
 *   <bundleDir>/worker/<name>     Worker code (esm | cjs | text | data | wasm | sourcemap)
 *   <bundleDir>/<assets.dir>/**   static files (Workers static assets)
 *
 * Limits: the whole bundle ≤ 50 MB, ≤ 5000 asset files, each asset ≤ 25 MiB; only safe relative paths, no symlinks, every
 * file must be inside the bundle (checked with realpath). Asset hash as in wrangler / Cloudflare's Direct Upload docs
 * (developers.cloudflare.com/workers/static-assets/direct-upload): sha256(base64(content) + file extension without the dot),
 * first 32 hex characters.
 * Error: CloudError('CF_BUNDLE_INVALID', a Vietnamese message naming the exact field / file). No Electron dependency.
 */
import * as crypto from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import { CloudError } from '../contracts';
import { BINDING_NAME_RE } from './validate';
import { tr } from '../../../shared/i18n';

export const BUNDLE_FILE = 'bundle.json';
export const BUNDLE_WORKER_DIR = 'worker';

export interface BundleLimits {
    maxTotalBytes: number;
    maxAssetFiles: number;
    maxAssetBytes: number;
    maxModules: number;
    maxBundleJsonBytes: number;
}

export const BUNDLE_LIMITS: BundleLimits = {
    maxTotalBytes: 50 * 1024 * 1024,
    maxAssetFiles: 5000,
    maxAssetBytes: 25 * 1024 * 1024,
    maxModules: 100,
    maxBundleJsonBytes: 256 * 1024,
};

export const MIGRATION_LIMITS = { maxFiles: 1000, maxFileBytes: 1024 * 1024 };

export type BundleModuleType = 'esm' | 'cjs' | 'text' | 'data' | 'wasm' | 'sourcemap';

/** Content-Type of each module type when uploading the script (multipart): the types Cloudflare accepts. */
export const MODULE_CONTENT_TYPES: Readonly<Record<BundleModuleType, string>> = {
    esm: 'application/javascript+module',
    cjs: 'application/javascript',
    text: 'text/plain',
    data: 'application/octet-stream',
    wasm: 'application/wasm',
    sourcemap: 'application/source-map',
};

/** The assets.config key is passed through unchanged to Cloudflare (metadata.assets.config of the Script Upload API). */
export const ASSET_CONFIG_KEYS = ['html_handling', 'not_found_handling', 'run_worker_first', '_headers', '_redirects'] as const;
const HTML_HANDLING = ['auto-trailing-slash', 'force-trailing-slash', 'drop-trailing-slash', 'none'];
const NOT_FOUND_HANDLING = ['none', '404-page', 'single-page-application'];

/** Files generated by the OS / tools: not uploaded. */
const IGNORED_ASSET_NAMES = new Set(['.DS_Store', 'Thumbs.db', 'desktop.ini', '.assetsignore']);

const COMPAT_DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const COMPAT_FLAG_RE = /^[a-z0-9_]{1,64}$/;
const MIGRATION_NAME_RE = /^[A-Za-z0-9][A-Za-z0-9._-]{0,199}$/;

/**
 * Cron Triggers per bundle. Cloudflare's Free plan has only 5 triggers for the WHOLE account (Paid: 250), so an app should
 * use one schedule and dispatch its jobs inside the Worker; 3 leaves room for the user's other Workers.
 */
export const CRON_LIMITS = { maxCrons: 3, maxLength: 100 } as const;
/** One field of a 5-field cron: digits, names (MON, JAN), * , - / and Cloudflare's L W # extensions. Cloudflare checks the meaning. */
const CRON_FIELD_RE = /^[0-9A-Za-z*,/#?-]{1,40}$/;

/** Shape check of one cron expression (already trimmed, single spaces): exactly 5 fields of allowed characters. */
export function isCronExpression(value: string): boolean {
    if (!value || value.length > CRON_LIMITS.maxLength) return false;
    const fields = value.split(' ');
    return fields.length === 5 && fields.every(f => CRON_FIELD_RE.test(f));
}

export interface BundleSpec {
    mainModule: string;
    modules: Array<{ name: string; type: BundleModuleType }>;
    compatibilityDate: string;
    compatibilityFlags: string[];
    assets: { dir: string; binding: string | null; config: Record<string, unknown> | null } | null;
    migrations: string | null;
    /** Cron Triggers to set on deploy; null = not declared (leave the Worker's schedules untouched). */
    crons: string[] | null;
}

export interface BundleModule {
    name: string;
    type: BundleModuleType;
    contentType: string;
    absPath: string;
    size: number;
}

export interface BundleAsset {
    /** Key in the manifest: "/index.html", "/assets/app-1a2b.js". */
    path: string;
    absPath: string;
    size: number;
    hash: string;
    contentType: string;
}

export interface WorkerBundle {
    dir: string;
    mainModule: string;
    compatibilityDate: string;
    compatibilityFlags: string[];
    modules: BundleModule[];
    assets: { dir: string; binding: string | null; config: Record<string, unknown> | null; files: BundleAsset[] } | null;
    migrations: string | null;
    /** Cron Triggers to set on deploy; null = not declared (leave the Worker's schedules untouched). */
    crons: string[] | null;
    totalBytes: number;
}

function invalid(message: string): CloudError {
    return new CloudError('CF_BUNDLE_INVALID', message);
}

function preview(v: unknown): string {
    return String(v ?? '').replace(/[\r\n\t]+/g, ' ').slice(0, 80);
}

function mb(bytes: number): string {
    return `${Math.round(bytes / 1024 / 1024)} MB`;
}

/** Strip the UTF-8 BOM at the start of the file (U+FEFF). */
export function stripBom(text: string): string {
    return text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
}

/** Safe relative path inside the bundle: "a/b.js" (not absolute, no "\\", ":", control characters, ".", "..", or empty segments). */
export function isSafeBundlePath(p: unknown, max = 300): p is string {
    if (typeof p !== 'string' || !p || p.length > max) return false;
    if (p.startsWith('/') || /[\\:]/.test(p) || /[\u0000-\u001f\u007f]/.test(p)) return false;
    return p.split('/').every(seg => seg !== '' && seg !== '.' && seg !== '..');
}

/** Asset hash (32 hex) as in wrangler: sha256(base64(content) + file extension without the dot). */
export function assetHash(content: Buffer, filePath: string): string {
    const extension = path.extname(filePath).slice(1);
    return crypto.createHash('sha256').update(content.toString('base64') + extension).digest('hex').slice(0, 32);
}

const ASSET_TYPES: Record<string, string> = {
    html: 'text/html', htm: 'text/html', css: 'text/css', js: 'text/javascript', mjs: 'text/javascript', cjs: 'text/javascript',
    json: 'application/json', map: 'application/json', webmanifest: 'application/manifest+json', txt: 'text/plain',
    xml: 'application/xml', csv: 'text/csv', md: 'text/markdown',
    svg: 'image/svg+xml', png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', gif: 'image/gif', webp: 'image/webp',
    avif: 'image/avif', ico: 'image/x-icon', bmp: 'image/bmp',
    woff: 'font/woff', woff2: 'font/woff2', ttf: 'font/ttf', otf: 'font/otf', eot: 'application/vnd.ms-fontobject',
    wasm: 'application/wasm', pdf: 'application/pdf', zip: 'application/zip',
    mp3: 'audio/mpeg', wav: 'audio/wav', ogg: 'audio/ogg', m4a: 'audio/mp4', mp4: 'video/mp4', webm: 'video/webm',
};

/**
 * Content-Type sent with each asset file (Cloudflare keeps it to serve the file). text/* adds charset=utf-8 as wrangler does;
 * unknown type → 'application/null' (Cloudflare: no Content-Type is sent when serving).
 */
export function assetContentType(filePath: string): string {
    const type = ASSET_TYPES[path.extname(filePath).slice(1).toLowerCase()];
    if (!type) return 'application/null';
    return type.startsWith('text/') ? `${type}; charset=utf-8` : type;
}

function inferModuleType(name: string): BundleModuleType | null {
    if (/\.m?js$/i.test(name)) return 'esm';
    if (/\.cjs$/i.test(name)) return 'cjs';
    if (/\.wasm$/i.test(name)) return 'wasm';
    if (/\.map$/i.test(name)) return 'sourcemap';
    return null;
}

function checkAssetConfig(cfg: unknown, errors: string[]): Record<string, unknown> | null {
    if (cfg === undefined || cfg === null) return null;
    if (typeof cfg !== 'object' || Array.isArray(cfg)) {
        errors.push(tr('assets.config phải là object'));
        return null;
    }
    const out: Record<string, unknown> = {};
    for (const [key, v] of Object.entries(cfg as Record<string, unknown>)) {
        switch (key) {
            case 'html_handling':
                if (typeof v === 'string' && HTML_HANDLING.includes(v)) out[key] = v;
                else errors.push(tr('assets.config.html_handling phải là {{v1}}', { v1: HTML_HANDLING.join(' | ') }));
                break;
            case 'not_found_handling':
                if (typeof v === 'string' && NOT_FOUND_HANDLING.includes(v)) out[key] = v;
                else errors.push(tr('assets.config.not_found_handling phải là {{v1}}', { v1: NOT_FOUND_HANDLING.join(' | ') }));
                break;
            case 'run_worker_first':
                if (typeof v === 'boolean') out[key] = v;
                else if (Array.isArray(v) && v.length >= 1 && v.length <= 100
                    && v.every(r => typeof r === 'string' && r.length <= 200 && (r.startsWith('/') || r.startsWith('!/')))) out[key] = [...v];
                else errors.push(tr('assets.config.run_worker_first phải là true / false hoặc mảng đường dẫn bắt đầu bằng "/" hoặc "!/"'));
                break;
            case '_headers':
            case '_redirects':
                if (typeof v === 'string' && v.length <= 100_000) out[key] = v;
                else errors.push(tr('assets.config.{{key}} phải là chuỗi tối đa 100000 ký tự', { key }));
                break;
            default:
                errors.push(tr('assets.config.{{v1}} không được hỗ trợ (chỉ {{v2}})', { v1: preview(key), v2: ASSET_CONFIG_KEYS.join(', ') }));
        }
    }
    return out;
}

/** Check the content of bundle.json (reads no other file). */
export function validateBundleJson(raw: unknown, limits: BundleLimits = BUNDLE_LIMITS): { ok: true; spec: BundleSpec } | { ok: false; errors: string[] } {
    const errors: string[] = [];
    if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return { ok: false, errors: [tr('phải là một object JSON')] };
    const o = raw as Record<string, any>;

    const modules: BundleSpec['modules'] = [];
    if (!Array.isArray(o.modules) || o.modules.length === 0 || o.modules.length > limits.maxModules) {
        errors.push(tr('modules phải là mảng 1–{{maxModules}} phần tử', { maxModules: limits.maxModules }));
    } else {
        const seen = new Set<string>();
        o.modules.forEach((m: any, i: number) => {
            const name = m?.name;
            if (!isSafeBundlePath(name, 200)) {
                errors.push(tr('modules[{{i}}].name phải là đường dẫn tương đối an toàn trong {{BUNDLE_WORKER_DIR}}/ (không "..", không tuyệt đối)', { i, BUNDLE_WORKER_DIR }));
                return;
            }
            if (seen.has(name)) {
                errors.push(tr('modules[{{i}}].name trùng "{{name}}"', { i, name }));
                return;
            }
            seen.add(name);
            const type = m?.type === undefined ? inferModuleType(name) : m.type;
            if (!type || !Object.prototype.hasOwnProperty.call(MODULE_CONTENT_TYPES, type)) {
                errors.push(tr('modules[{{i}}].type phải là {{v1}}', { i, v1: Object.keys(MODULE_CONTENT_TYPES).join(' | ') }));
                return;
            }
            modules.push({ name, type: type as BundleModuleType });
        });
    }

    const mainModule = o.mainModule;
    if (typeof mainModule !== 'string' || !mainModule) errors.push(tr('thiếu mainModule'));
    else if (Array.isArray(o.modules) && !o.modules.some((m: any) => m?.name === mainModule)) errors.push(tr('mainModule "{{v1}}" không có trong modules', { v1: preview(mainModule) }));
    else if (modules.length && !['esm', 'cjs'].includes(modules.find(m => m.name === mainModule)?.type || 'esm')) errors.push(tr('mainModule phải là module mã (esm hoặc cjs)'));

    const date = o.compatibilityDate;
    if (typeof date !== 'string' || !COMPAT_DATE_RE.test(date) || Number.isNaN(Date.parse(`${date}T00:00:00Z`))) {
        errors.push(tr('compatibilityDate phải có dạng YYYY-MM-DD'));
    }

    let flags: string[] = [];
    if (o.compatibilityFlags !== undefined) {
        if (!Array.isArray(o.compatibilityFlags) || o.compatibilityFlags.length > 20 || o.compatibilityFlags.some((f: any) => typeof f !== 'string' || !COMPAT_FLAG_RE.test(f))) {
            errors.push(tr('compatibilityFlags phải là mảng tối đa 20 cờ (a-z, 0-9, _)'));
        } else {
            flags = Array.from(new Set(o.compatibilityFlags as string[]));
        }
    }

    let assets: BundleSpec['assets'] = null;
    if (o.assets !== undefined && o.assets !== null) {
        const a = o.assets;
        if (typeof a !== 'object' || Array.isArray(a)) errors.push(tr('assets phải là object'));
        else {
            if (!isSafeBundlePath(a.dir, 200)) errors.push(tr('assets.dir phải là thư mục tương đối an toàn trong gói, vd "assets"'));
            let binding: string | null = null;
            if (a.binding !== undefined && a.binding !== null && a.binding !== '') {
                if (typeof a.binding !== 'string' || !BINDING_NAME_RE.test(a.binding)) errors.push(tr('assets.binding chỉ gồm chữ, số, "_" và không bắt đầu bằng số'));
                else binding = a.binding;
            }
            const config = checkAssetConfig(a.config, errors);
            if (isSafeBundlePath(a.dir, 200)) assets = { dir: a.dir, binding, config };
        }
    }

    let migrations: string | null = null;
    if (o.migrations !== undefined && o.migrations !== null) {
        if (!isSafeBundlePath(o.migrations, 200)) errors.push(tr('migrations phải là thư mục tương đối an toàn trong gói'));
        else migrations = o.migrations;
    }

    let crons: string[] | null = null;
    if (o.crons !== undefined && o.crons !== null) {
        const list = Array.isArray(o.crons)
            ? o.crons.map((c: unknown) => (typeof c === 'string' ? c.trim().replace(/\s+/g, ' ') : ''))
            : null;
        if (!list || list.length > CRON_LIMITS.maxCrons || list.some((c: string) => !isCronExpression(c))) {
            errors.push(tr('crons phải là mảng tối đa {{maxCrons}} biểu thức cron 5 trường, vd "*/5 * * * *"', { maxCrons: CRON_LIMITS.maxCrons }));
        } else {
            crons = Array.from(new Set<string>(list));
        }
    }

    if (errors.length) return { ok: false, errors };
    return {
        ok: true,
        spec: { mainModule, modules, compatibilityDate: date, compatibilityFlags: flags, assets, migrations, crons },
    };
}

function isInside(child: string, parent: string): boolean {
    return child === parent || child.startsWith(parent + path.sep);
}

/** Root folder (bundle / migrations) whose location the caller has already checked: must exist and be a folder; returns the realpath. */
function realRoot(p: string, label: string): string {
    let real: string;
    try {
        real = fs.realpathSync(p);
    } catch {
        throw invalid(tr('Không thấy {{label}}', { label }));
    }
    if (!fs.statSync(real).isDirectory()) throw invalid(tr('{{label}} không phải thư mục', { label }));
    return real;
}

/** Subfolder inside the bundle: no symlinks; the realpath must be inside `within`. */
function subDirectory(within: string, rel: string, label: string): string {
    const full = path.join(within, ...rel.split('/'));
    let st: fs.Stats;
    try {
        st = fs.lstatSync(full);
    } catch {
        throw invalid(tr('Không thấy {{label}}', { label }));
    }
    if (st.isSymbolicLink()) throw invalid(tr('{{label}} không được là symlink', { label }));
    if (!st.isDirectory()) throw invalid(tr('{{label}} không phải thư mục', { label }));
    const real = fs.realpathSync(full);
    if (!isInside(real, within)) throw invalid(tr('{{label}} nằm ngoài gói Worker', { label }));
    return real;
}

function regularFileInside(base: string, rel: string, label: string): string {
    const full = path.join(base, ...rel.split('/'));
    let st: fs.Stats;
    try {
        st = fs.lstatSync(full);
    } catch {
        throw invalid(tr('Không thấy file {{label}}', { label }));
    }
    if (st.isSymbolicLink() || !st.isFile()) throw invalid(tr('{{label}} phải là file thường (không symlink)', { label }));
    const real = fs.realpathSync(full);
    if (!isInside(real, base)) throw invalid(tr('{{label}} nằm ngoài gói Worker', { label }));
    return real;
}

function walkAssets(dirAbs: string, rel: string, out: BundleAsset[], limits: BundleLimits, addBytes: (n: number) => void): void {
    const entries = fs.readdirSync(dirAbs, { withFileTypes: true })
        .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    for (const ent of entries) {
        if (IGNORED_ASSET_NAMES.has(ent.name)) continue;
        const relPath = rel ? `${rel}/${ent.name}` : ent.name;
        if (!isSafeBundlePath(relPath, 1000)) throw invalid(tr('Tên file asset không hợp lệ: "{{v1}}"', { v1: preview(relPath) }));
        const abs = path.join(dirAbs, ent.name);
        if (ent.isSymbolicLink()) throw invalid(tr('Asset "{{relPath}}" là symlink — gói chỉ được chứa file thường', { relPath }));
        if (ent.isDirectory()) {
            walkAssets(abs, relPath, out, limits, addBytes);
            continue;
        }
        if (!ent.isFile()) throw invalid(tr('Asset "{{relPath}}" không phải file thường', { relPath }));
        const size = fs.statSync(abs).size;
        if (size > limits.maxAssetBytes) throw invalid(tr('Asset "{{relPath}}" vượt {{v1}} (giới hạn mỗi file của Cloudflare)', { relPath, v1: mb(limits.maxAssetBytes) }));
        if (out.length >= limits.maxAssetFiles) throw invalid(tr('Gói có quá {{maxAssetFiles}} file asset', { maxAssetFiles: limits.maxAssetFiles }));
        addBytes(size);
        const content = fs.readFileSync(abs);
        out.push({ path: `/${relPath}`, absPath: abs, size, hash: assetHash(content, ent.name), contentType: assetContentType(ent.name) });
    }
}

/**
 * Reads + checks the bundle: bundle.json, modules in worker/, all assets (hashes computed). `dir` is the bundle folder, whose location the caller
 * has already checked (bridge: inside the app folder). Asset contents are not kept in RAM (re-read when uploading).
 */
export function readBundle(dir: string, limits: BundleLimits = BUNDLE_LIMITS): WorkerBundle {
    const root = realRoot(dir, tr('thư mục gói Worker'));
    const jsonPath = path.join(root, BUNDLE_FILE);
    let st: fs.Stats;
    try {
        st = fs.lstatSync(jsonPath);
    } catch {
        throw invalid(tr('Không thấy {{BUNDLE_FILE}} trong thư mục gói Worker', { BUNDLE_FILE }));
    }
    if (!st.isFile()) throw invalid(tr('{{BUNDLE_FILE}} phải là file thường', { BUNDLE_FILE }));
    if (st.size > limits.maxBundleJsonBytes) throw invalid(tr('{{BUNDLE_FILE}} quá lớn', { BUNDLE_FILE }));
    let raw: unknown;
    try {
        raw = JSON.parse(stripBom(fs.readFileSync(jsonPath, 'utf8')));
    } catch (err: any) {
        throw invalid(tr('{{BUNDLE_FILE}} không phải JSON hợp lệ: {{v1}}', { BUNDLE_FILE, v1: preview(err?.message || err) }));
    }
    const res = validateBundleJson(raw, limits);
    if (res.ok === false) throw invalid(tr('{{BUNDLE_FILE}} không hợp lệ: {{v1}}', { BUNDLE_FILE, v1: res.errors.slice(0, 5).join('; ') }));
    const spec = res.spec;

    let total = 0;
    const addBytes = (n: number) => {
        total += n;
        if (total > limits.maxTotalBytes) throw invalid(tr('Gói Worker vượt {{v1}}', { v1: mb(limits.maxTotalBytes) }));
    };

    const workerRoot = subDirectory(root, BUNDLE_WORKER_DIR, tr('thư mục {{BUNDLE_WORKER_DIR}}/ của gói', { BUNDLE_WORKER_DIR }));
    const modules: BundleModule[] = spec.modules.map(m => {
        const absPath = regularFileInside(workerRoot, m.name, `module "${m.name}" (${BUNDLE_WORKER_DIR}/${m.name})`);
        const size = fs.statSync(absPath).size;
        addBytes(size);
        return { name: m.name, type: m.type, contentType: MODULE_CONTENT_TYPES[m.type], absPath, size };
    });

    let assets: WorkerBundle['assets'] = null;
    if (spec.assets) {
        const assetsRoot = subDirectory(root, spec.assets.dir, tr('thư mục asset "{{dir}}"', { dir: spec.assets.dir }));
        const files: BundleAsset[] = [];
        walkAssets(assetsRoot, '', files, limits, addBytes);
        if (!files.length) throw invalid(tr('Thư mục asset "{{dir}}" không có file nào', { dir: spec.assets.dir }));
        assets = { dir: assetsRoot, binding: spec.assets.binding, config: spec.assets.config, files };
    }

    return {
        dir: root,
        mainModule: spec.mainModule,
        compatibilityDate: spec.compatibilityDate,
        compatibilityFlags: spec.compatibilityFlags,
        modules,
        assets,
        migrations: spec.migrations,
        crons: spec.crons,
        totalBytes: total,
    };
}

/**
 * Migration files *.sql in the folder (sorted by name as in wrangler). The name is written to d1_migrations, so only letters, digits,
 * ". _ -" are accepted; each file ≤ 1 MB, no symlinks. `dir` has already been location-checked by the caller.
 */
export function listMigrationFiles(dir: string, limits = MIGRATION_LIMITS): Array<{ name: string; absPath: string; size: number }> {
    const root = realRoot(dir, tr('thư mục migration'));
    const out: Array<{ name: string; absPath: string; size: number }> = [];
    for (const ent of fs.readdirSync(root, { withFileTypes: true })) {
        if (!ent.name.endsWith('.sql')) continue;
        if (!MIGRATION_NAME_RE.test(ent.name)) throw invalid(tr('Tên file migration "{{v1}}" chỉ được gồm chữ, số, ". _ -"', { v1: preview(ent.name) }));
        if (ent.isSymbolicLink() || !ent.isFile()) throw invalid(tr('Migration "{{name}}" phải là file thường (không symlink)', { name: ent.name }));
        const absPath = path.join(root, ent.name);
        const size = fs.statSync(absPath).size;
        if (size > limits.maxFileBytes) throw invalid(tr('Migration "{{name}}" vượt {{v1}}', { name: ent.name, v1: mb(limits.maxFileBytes) }));
        out.push({ name: ent.name, absPath, size });
        if (out.length > limits.maxFiles) throw invalid(tr('Quá {{maxFiles}} file migration', { maxFiles: limits.maxFiles }));
    }
    return out.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}
