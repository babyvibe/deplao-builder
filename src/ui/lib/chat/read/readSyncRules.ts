/**
 * Pure rules for syncing "đã đọc" (read) to the platform (liveReadSync): whether the user is at the machine, how long to wait, which message
 * is used as the Zalo "đã xem" (seen) mark, and the payload sent. Imports no store / IPC, so it can be tested directly.
 */

/** Mouse / keyboard activity within this window counts as watching the screen (if the user walked away, nothing is reported as read in their place). */
export const PRESENCE_WINDOW_MS = 60_000;
/** New message in the open conversation: wait a moment so the whole batch is reported in one go. */
export const LIVE_READ_DELAY_MS = 800;
/** The user acts again (after refocusing / sitting still): reported almost at once. */
export const PRESENCE_RESUME_DELAY_MS = 300;

/** Each conversation is reported as read at most once in this window (each Telegram report is 1–3 MTProto calls). */
const MIN_READ_INTERVAL_MS: Record<string, number> = {
  zalo: 1_500,
  facebook: 2_000,
  telegram_user: 3_000,
};

/** A message that is not a real platform message (generated by Deplao / recalled) → not used as the "đã xem" (seen) mark. */
const NOT_SEEABLE_TYPES = new Set(['system', 'recalled', 'undo', 'deleted']);

export interface ReadThreadRef {
  accountId: string;
  threadId: string;
  /** 0 = 1:1, 1 = group */
  threadType: number;
  /** Telegram forum: the open topic (activeTopicId), null for a normal conversation */
  topicId?: string | null;
}

/** A received message (from someone else) used as the read mark. */
export interface IncomingRef {
  msgId: string;
  cliMsgId?: string;
  senderId: string;
  msgType?: string;
  ts?: number;
}

/** Minimal message row (DB / store) used to pick the mark. */
export interface ReadRow {
  msg_id?: string | null;
  cli_msg_id?: string | null;
  sender_id?: string | null;
  msg_type?: string | null;
  timestamp?: number | null;
  is_sent?: number | null;
}

/** A channel with a read-report API (Telegram Bot has no read state on the platform). */
export function supportsPlatformRead(channel: string | undefined): boolean {
  return channel === 'zalo' || channel === 'facebook' || channel === 'telegram_user';
}

export function minReadIntervalMs(channel: string | undefined): number {
  return MIN_READ_INTERVAL_MS[channel || ''] ?? 2_000;
}

export function isUserPresent(now: number, lastInputAt: number, windowMs = PRESENCE_WINDOW_MS): boolean {
  return lastInputAt > 0 && now - lastInputAt <= windowMs;
}

/** Wait time before the next report: at least `baseDelay`, and not earlier than the previous report plus the channel's minimum gap. */
export function readSyncDelay(now: number, lastSyncAt: number, minIntervalMs: number, baseDelay: number): number {
  const throttleUntil = lastSyncAt > 0 ? lastSyncAt + minIntervalMs : 0;
  return Math.max(baseDelay, throttleUntil - now, 0);
}

function isIncomingRow(row: ReadRow, ownUid: string): boolean {
  const msgId = String(row.msg_id || '');
  const sender = String(row.sender_id || '');
  if (!msgId || msgId.startsWith('temp_')) return false;
  if (Number(row.is_sent) === 1) return false;
  if (!sender || sender === '0' || (ownUid && sender === ownUid)) return false;
  return !NOT_SEEABLE_TYPES.has(String(row.msg_type || ''));
}

/**
 * Newest received message (skipping my own messages, system messages / recalled messages, temporary messages with no id). The order of `rows` does not matter (the DB returns
 * new → old, the store old → new); with the same timestamp, the row later in the array wins.
 */
export function newestIncoming(rows: ReadonlyArray<ReadRow> | null | undefined, ownUid: string): IncomingRef | null {
  let best: ReadRow | null = null;
  let bestTs = -Infinity;
  for (const row of rows || []) {
    if (!isIncomingRow(row, ownUid)) continue;
    const ts = Number(row.timestamp) || 0;
    if (!best || ts >= bestTs) {
      best = row;
      bestTs = ts;
    }
  }
  if (!best) return null;
  return {
    msgId: String(best.msg_id),
    cliMsgId: best.cli_msg_id ? String(best.cli_msg_id) : undefined,
    senderId: String(best.sender_id),
    msgType: best.msg_type ? String(best.msg_type) : undefined,
    ts: Number(best.timestamp) || undefined,
  };
}

/** Which message is newer (by time; without a time, the one that came later wins). */
export function newerIncoming(current: IncomingRef | null | undefined, next: IncomingRef): IncomingRef {
  if (!current) return next;
  return (Number(next.ts) || 0) >= (Number(current.ts) || 0) ? next : current;
}

/**
 * Payload for one message sent to zca-js sendSeenEvent. zca-js takes the 1:1 conversation from `uidFrom` (must be the sender = the customer, not
 * me) and the group from `idTo` (= the group id); the recipient of a 1:1 message is me itself, and Zalo records "0" (before, the customer's id was sent).
 */
export function zaloSeenPayload(target: IncomingRef, ref: ReadThreadRef) {
  return {
    msgId: target.msgId,
    cliMsgId: target.cliMsgId || target.msgId,
    uidFrom: target.senderId,
    idTo: ref.threadType === 1 ? ref.threadId : '0',
    msgType: target.msgType || 'webchat',
    st: 0,
    at: 0,
    cmd: 0,
    ts: target.ts || Date.now(),
  };
}
